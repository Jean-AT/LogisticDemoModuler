CREATE SCHEMA logistica;

CREATE TABLE logistica.suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    code VARCHAR(30) NOT NULL,
    name VARCHAR(180) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    source_system VARCHAR(40) NOT NULL DEFAULT 'MVP1',
    legacy_id BIGINT,
    version BIGINT NOT NULL DEFAULT 0,
    created_by VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_logistics_supplier_code UNIQUE (company_id, code),
    CONSTRAINT uk_logistics_supplier_legacy UNIQUE (source_system, legacy_id),
    CONSTRAINT fk_logistics_supplier_company FOREIGN KEY (company_id)
        REFERENCES platform.companies(id),
    CONSTRAINT ck_logistics_supplier_source CHECK (source_system IN ('MVP1', 'LEGACY_DEMO')),
    CONSTRAINT ck_logistics_supplier_not_blank CHECK (BTRIM(code) <> '' AND BTRIM(name) <> '')
);

