CREATE TABLE logistica.requisition_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requisition_id BIGINT NOT NULL,
    line_number INTEGER NOT NULL,
    needs_plan_id BIGINT,
    needs_line_id BIGINT,
    monthly_need_id BIGINT,
    catalog_item_id BIGINT NOT NULL,
    warehouse_id BIGINT,
    requested_quantity NUMERIC(18, 4) NOT NULL,
    approved_quantity NUMERIC(18, 4) NOT NULL DEFAULT 0,
    unit_price_estimated NUMERIC(18, 4) NOT NULL,
    subtotal_estimated NUMERIC(18, 2) NOT NULL,
    source_system VARCHAR(40) NOT NULL DEFAULT 'MVP1',
    legacy_id BIGINT,
    CONSTRAINT uk_logistics_requisition_line_number UNIQUE (requisition_id, line_number),
    CONSTRAINT uk_logistics_requisition_line_legacy UNIQUE (source_system, legacy_id),
    CONSTRAINT fk_logistics_requisition_line_requisition FOREIGN KEY (requisition_id)
        REFERENCES logistica.requisitions(id),
    CONSTRAINT fk_logistics_requisition_line_item FOREIGN KEY (catalog_item_id)
        REFERENCES platform.catalog_items(id),
    CONSTRAINT fk_logistics_requisition_line_warehouse FOREIGN KEY (warehouse_id)
        REFERENCES logistica.warehouses(id),
    CONSTRAINT ck_logistics_requisition_line_quantities CHECK (
        requested_quantity > 0
        AND approved_quantity >= 0
        AND approved_quantity <= requested_quantity
        AND unit_price_estimated >= 0
        AND subtotal_estimated >= 0
    ),
    CONSTRAINT ck_logistics_requisition_line_source CHECK (source_system IN ('MVP1', 'LEGACY_DEMO'))
);

