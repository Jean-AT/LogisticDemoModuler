INSERT INTO logistica.requisitions (
    company_id, fiscal_year, number, description, supplier_id, currency_code,
    status, source_system, legacy_id, created_by, created_at, updated_by, updated_at
)
SELECT c.id,
       EXTRACT(YEAR FROM legacy.created_at)::SMALLINT,
       COALESCE(legacy.numero, 'LEGACY-REQ-' || legacy.id::TEXT),
       legacy.descripcion,
       supplier.id,
       SUBSTRING(legacy.moneda FROM 1 FOR 3),
       'LEGACY_IMPORTED',
       'LEGACY_DEMO',
       legacy.id,
       legacy.created_by,
       legacy.created_at,
       legacy.updated_by,
       legacy.updated_at
FROM logistica_demo.requerimientos legacy
JOIN platform.companies c ON c.code = 'DEMO'
JOIN logistica.suppliers supplier
  ON supplier.source_system = 'LEGACY_DEMO'
 AND supplier.legacy_id = legacy.proveedor_id;

INSERT INTO logistica.requisition_lines (
    requisition_id, line_number, catalog_item_id, warehouse_id,
    requested_quantity, approved_quantity, unit_price_estimated, subtotal_estimated,
    source_system, legacy_id
)
SELECT requisition.id,
       ROW_NUMBER() OVER (PARTITION BY legacy.requerimiento_id ORDER BY legacy.id),
       catalog_item.id,
       warehouse.id,
       legacy.cantidad,
       legacy.cantidad,
       legacy.precio_unitario_estimado,
       legacy.subtotal_linea,
       'LEGACY_DEMO',
       legacy.id
FROM logistica_demo.requerimiento_detalles legacy
JOIN logistica.requisitions requisition
  ON requisition.source_system = 'LEGACY_DEMO'
 AND requisition.legacy_id = legacy.requerimiento_id
JOIN logistica_demo.items legacy_item ON legacy_item.id = legacy.item_id
JOIN platform.catalog_items catalog_item
  ON catalog_item.company_id = requisition.company_id
 AND catalog_item.code = legacy_item.code
JOIN logistica.warehouses warehouse
  ON warehouse.source_system = 'LEGACY_DEMO'
