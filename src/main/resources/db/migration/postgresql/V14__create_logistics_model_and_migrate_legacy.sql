DO $$
DECLARE
    legacy_suppliers_count INTEGER;
    migrated_suppliers_count INTEGER;
    legacy_warehouses_count INTEGER;
    migrated_warehouses_count INTEGER;
    legacy_requisitions_count INTEGER;
    migrated_requisitions_count INTEGER;
    legacy_requisition_lines_count INTEGER;
    migrated_requisition_lines_count INTEGER;
    legacy_purchase_orders_count INTEGER;
    migrated_purchase_orders_count INTEGER;
    unresolved_requisition_lines_count INTEGER;
BEGIN
    SELECT COUNT(*) INTO legacy_suppliers_count FROM logistica_demo.proveedores;
    SELECT COUNT(*) INTO migrated_suppliers_count FROM logistica.suppliers WHERE source_system = 'LEGACY_DEMO';
    SELECT COUNT(*) INTO legacy_warehouses_count FROM logistica_demo.almacenes;
    SELECT COUNT(*) INTO migrated_warehouses_count FROM logistica.warehouses WHERE source_system = 'LEGACY_DEMO';
    SELECT COUNT(*) INTO legacy_requisitions_count FROM logistica_demo.requerimientos;
    SELECT COUNT(*) INTO migrated_requisitions_count FROM logistica.requisitions WHERE source_system = 'LEGACY_DEMO';
    SELECT COUNT(*) INTO legacy_requisition_lines_count FROM logistica_demo.requerimiento_detalles;
    SELECT COUNT(*) INTO migrated_requisition_lines_count FROM logistica.requisition_lines WHERE source_system = 'LEGACY_DEMO';
    SELECT COUNT(*) INTO legacy_purchase_orders_count FROM logistica_demo.ordenes_compra;
    SELECT COUNT(*) INTO migrated_purchase_orders_count FROM logistica.purchase_orders WHERE source_system = 'LEGACY_DEMO';
    SELECT COUNT(*) INTO unresolved_requisition_lines_count
    FROM logistica.requisition_lines
    WHERE source_system = 'LEGACY_DEMO'
      AND (catalog_item_id IS NULL OR warehouse_id IS NULL);

    IF migrated_suppliers_count <> legacy_suppliers_count THEN
        RAISE EXCEPTION 'LOG-T02 validation failed: migrated suppliers %, expected %',
            migrated_suppliers_count, legacy_suppliers_count;
    END IF;
    IF migrated_warehouses_count <> legacy_warehouses_count THEN
        RAISE EXCEPTION 'LOG-T02 validation failed: migrated warehouses %, expected %',
            migrated_warehouses_count, legacy_warehouses_count;
    END IF;
    IF migrated_requisitions_count <> legacy_requisitions_count THEN
        RAISE EXCEPTION 'LOG-T02 validation failed: migrated requisitions %, expected %',
            migrated_requisitions_count, legacy_requisitions_count;
    END IF;
    IF migrated_requisition_lines_count <> legacy_requisition_lines_count THEN
        RAISE EXCEPTION 'LOG-T02 validation failed: migrated requisition lines %, expected %',
            migrated_requisition_lines_count, legacy_requisition_lines_count;
    END IF;
    IF migrated_purchase_orders_count <> legacy_purchase_orders_count THEN
        RAISE EXCEPTION 'LOG-T02 validation failed: migrated purchase orders %, expected %',
            migrated_purchase_orders_count, legacy_purchase_orders_count;
    END IF;
    IF unresolved_requisition_lines_count <> 0 THEN
        RAISE EXCEPTION 'LOG-T02 validation failed: % legacy requisition lines without item or warehouse',
            unresolved_requisition_lines_count;
    END IF;
END $$;
