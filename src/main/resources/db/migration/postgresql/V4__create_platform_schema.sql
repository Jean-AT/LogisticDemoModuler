CREATE SCHEMA platform;

CREATE TABLE platform.companies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL,
    legal_name VARCHAR(200) NOT NULL,
    trade_name VARCHAR(200),
    tax_id VARCHAR(20),
    timezone VARCHAR(50) NOT NULL DEFAULT 'America/Lima',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    created_by VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_company_code UNIQUE (code),
    CONSTRAINT uk_company_tax_id UNIQUE (tax_id),
    CONSTRAINT ck_company_code_not_blank CHECK (BTRIM(code) <> ''),
    CONSTRAINT ck_company_legal_name_not_blank CHECK (BTRIM(legal_name) <> '')
);

CREATE TABLE platform.organization_units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    parent_id BIGINT,
    code VARCHAR(30) NOT NULL,
    name VARCHAR(160) NOT NULL,
    unit_type VARCHAR(30) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    created_by VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_organization_unit_company_code UNIQUE (company_id, code),
    CONSTRAINT uk_organization_unit_company_id UNIQUE (company_id, id),
    CONSTRAINT fk_organization_unit_company FOREIGN KEY (company_id)
        REFERENCES platform.companies(id),
    CONSTRAINT fk_organization_unit_parent FOREIGN KEY (company_id, parent_id)
        REFERENCES platform.organization_units(company_id, id),
    CONSTRAINT ck_organization_unit_code_not_blank CHECK (BTRIM(code) <> ''),
    CONSTRAINT ck_organization_unit_name_not_blank CHECK (BTRIM(name) <> ''),
    CONSTRAINT ck_organization_unit_not_self_parent CHECK (parent_id IS NULL OR parent_id <> id)
);

CREATE TABLE platform.cost_centers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id BIGINT NOT NULL,
    organization_unit_id BIGINT NOT NULL,
    code VARCHAR(30) NOT NULL,
    name VARCHAR(160) NOT NULL,
    valid_from DATE,
    valid_to DATE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    created_by VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_cost_center_company_code UNIQUE (company_id, code),
    CONSTRAINT uk_cost_center_company_id UNIQUE (company_id, id),
    CONSTRAINT fk_cost_center_company FOREIGN KEY (company_id)
        REFERENCES platform.companies(id),
    CONSTRAINT fk_cost_center_organization_unit FOREIGN KEY (company_id, organization_unit_id)
        REFERENCES platform.organization_units(company_id, id),
    CONSTRAINT ck_cost_center_code_not_blank CHECK (BTRIM(code) <> ''),
    CONSTRAINT ck_cost_center_name_not_blank CHECK (BTRIM(name) <> ''),
    CONSTRAINT ck_cost_center_validity CHECK (valid_to IS NULL OR valid_from IS NULL OR valid_to >= valid_from)
);

