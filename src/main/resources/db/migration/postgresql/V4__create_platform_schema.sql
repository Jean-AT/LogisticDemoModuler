    item_type VARCHAR(20) NOT NULL DEFAULT 'GOOD',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    created_by VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by VARCHAR(100) NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_catalog_item_company_code UNIQUE (company_id, code),
    CONSTRAINT fk_catalog_item_company FOREIGN KEY (company_id) REFERENCES platform.companies(id),
    CONSTRAINT fk_catalog_item_unit FOREIGN KEY (unit_of_measure_id) REFERENCES platform.units_of_measure(id),
    CONSTRAINT fk_catalog_item_classifier FOREIGN KEY (company_id, expense_classifier_id)
        REFERENCES platform.expense_classifiers(company_id, id),
    CONSTRAINT ck_catalog_item_code_not_blank CHECK (BTRIM(code) <> ''),
    CONSTRAINT ck_catalog_item_name_not_blank CHECK (BTRIM(name) <> ''),
